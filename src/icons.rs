const DEFAULT: &'static str = "\u{f15b}";

pub fn get_icon(name: &str) -> &'static str {
    ICONS
        .iter()
        .find(|(suf, _)| name.ends_with(suf))
        .map(|v| v.1)
        .unwrap_or(DEFAULT)
}

pub fn dir_icon() -> &'static str {
    "\u{f07b}"
}
